# Load the test data from the saved JSON file
def load_data(filename):
    with open(filename, 'r') as file:
        data = json.load(file)
    return data['data']

test_data = load_data('/content/Q&A_Dataset_test.json')

# Correctly format the data for Simple Transformers
formatted_test_data = []
for entry in test_data:
    context = entry["context"]
    for qa in entry["qas"]:
        formatted_test_data.append({
            "context": context,
            "qas": [qa]
        })

# Load the trained model from the specified checkpoint
model = QuestionAnsweringModel(
    "bert",
    "outputs/checkpoint-9-epoch-1",  # Adjust this to the path where your trained model is saved
    use_cuda=True
)

# Generate predictions
predictions = model.predict(formatted_test_data)


# Extract answers and probabilities from the tuple
answer_predictions, probability_predictions = predictions

# Print answers along with their corresponding probabilities
for answer, probability in zip(answer_predictions, probability_predictions):
    print(f"ID: {answer['id']}")
    print(f"Answer: {answer['answer'][0]}")  # Assuming there is always at least one answer
    print(f"Probability: {probability['probability'][0]}")  # Assuming there is always one probability
    print()  # Adds a blank line between each prediction for better readability