import logging
import random
import json
from simpletransformers.question_answering import QuestionAnsweringModel, QuestionAnsweringArgs

#Setting up logging to control the output of logs
logging.basicConfig(level=logging.INFO)
transformers_logger = logging.getLogger("transformers")
transformers_logger.setLevel(logging.WARNING)

# Define model arguments
model_args = QuestionAnsweringArgs()
model_args.n_best_size = 1  # Return only best answer from the model

# Initialize the model
model = QuestionAnsweringModel(
    "bert",
    "bert-base-uncased",
    args=model_args,
    use_cuda=True  # I have set it to false for now to use GPU, if true, uses CUDA-enabled GPU
)

# Function to load data from JSON files
def load_data(filename):
    with open(filename, 'r') as file:
        return json.load(file)["data"]



# Print the current working directory to help locate files if needed
import os
print(os.getcwd())

# Load the complete dataset
data = load_data('/content/Q&A_Dataset.json')


# Shuffle your data to ensure random distribution
random.shuffle(data)

# Calculate the number of questions to define training and validation set sizes
num_questions = len(data)
train_end = int(num_questions * 0.8)
val_end = train_end + int(num_questions * 0.1)



# Split the data into training, validation, and test sets
train_data = data[:train_end]
val_data = data[train_end:val_end]
test_data = data[val_end:]

# Function to save data to a file
def save_data(dataset, filename):
    with open(filename, 'w') as file:
        json.dump({"data": dataset}, file, indent=4)

# Save the split to separate files
save_data(train_data, '/content/Q&A_Dataset_train.json')
save_data(val_data, '/content/Q&A_Dataset_validation.json')
save_data(test_data, '/content/Q&A_Dataset_test.json')

# Train the model with the loaded datasets
model.train_model(train_data, eval_data=val_data)

# Install the transformers library
